#!/usr/bin/env python3
"""Generate flat 1-bpp transport icons for the Music Player.

Rasterizes Lucide SVGs (shuffle/repeat/skip/play/pause/...) into C++ constexpr
byte arrays: n*n pixels, rows top-to-bottom, MSB-first, bit 1 = white
(leave), bit 0 = ink. This is the format GfxRenderer::drawIcon uses and that
MusicPlayerActivity's local blitGlyph() plots; the freeink-sdk gen_icons.py
outputs the same packing wrapped in a freeink::Icon struct.

Usage:
    gen_transport_icons.py \\
        --svgdir freeink-sdk/libs/assets/Icons/lucide/icons \\
        --out src/components/icons/musicTransport.h

Requires: rsvg-convert (librsvg2-bin) and Pillow.
"""
import argparse
import io
import os
import subprocess
import sys

from PIL import Image

THRESHOLD = 110  # luminance below this on white counts as ink; keeps 2px strokes solid

# (C identifier, lucide SVG basename, pixel size)
ICONS = [
    ("shuffle", "shuffle", 40),
    ("repeat", "repeat", 40),
    ("repeatOne", "repeat-1", 40),
    ("prev", "skip-back", 40),
    ("next", "skip-forward", 40),
    ("play", "play", 36),
    ("pause", "pause", 36),
    ("check", "check", 28),
    ("chevron", "chevron-right", 28),
    ("note", "music", 40),
    ("music", "music", 96),
]


def rasterize(svg_path, px):
    png = subprocess.run(
        ["rsvg-convert", "-w", str(px), "-h", str(px), svg_path],
        capture_output=True,
        check=True,
    ).stdout
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    bg.paste(img, mask=img.split()[3])
    return bg.convert("L")


def pack(img):
    """1-bpp MSB-first rows; 1 = white, 0 = ink. Returns (bytes, width)."""
    px = img.load()
    w, h = img.size
    row_bytes = (w + 7) // 8
    data = bytearray()
    for row in range(h):
        for rb in range(row_bytes):
            byte = 0
            for bit in range(8):
                col = rb * 8 + bit
                if col >= w:
                    break  # padding stays 1 (white)
                if px[col, row] >= THRESHOLD:
                    byte |= 1 << (7 - bit)
            data.append(byte)
    return bytes(data), w


def emit(out_path, packed):
    lines = [
        "#pragma once",
        "",
        "// Auto-generated by scripts/gen_transport_icons.py - do not edit.",
        "// Source: Lucide icons (ISC license), flat n*n 1-bpp, MSB-first,",
        "// bit 1 = white, bit 0 = ink. See scripts/LICENSE.lucide if present.",
        "",
        "#include <cstdint>",
        "",
        "namespace MusicTransport {",
    ]
    for name, size, data in packed:
        lines.append(f"inline constexpr int {name}_size = {size};")
        lines.append(f"inline constexpr uint8_t {name}[] = {{")
        row_bytes = (size + 7) // 8
        per_row = 12
        flat = list(data)
        for i in range(0, len(flat), per_row):
            chunk = flat[i:i + per_row]
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace MusicTransport")
    lines.append("")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--svgdir", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    packed = []
    for name, svg, size in ICONS:
        svg_path = os.path.join(args.svgdir, svg + ".svg")
        if not os.path.exists(svg_path):
            print(f"missing SVG: {svg_path}", file=sys.stderr)
            return 1
        data, w = pack(rasterize(svg_path, size))
        packed.append((name, size, data))
        print(f"{name:10s} {size:3d}px  {len(data)} bytes")

    emit(args.out, packed)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
